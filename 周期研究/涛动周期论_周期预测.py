def wave(turns, x):
    """在拐点之间用半个余弦波插值，返回 x 处的相位值（-1 ~ +1）"""
    y = np.zeros_like(x, dtype=float)
    for i in range(len(turns) - 1):
        (t0, p0), (t1, p1) = turns[i], turns[i + 1]
        m = (x >= t0) & (x <= t1)
        frac = (x[m] - t0) / (t1 - t0)
        y[m] = p0 + (p1 - p0) * (1 - np.cos(np.pi * frac)) / 2
    y[x < turns[0][0]] = turns[0][1]
    y[x > turns[-1][0]] = turns[-1][1]
    return y


